import { expect, test } from '@playwright/test'

test('creates a payment link and filters the list by status', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel(/Amount/).fill('2499.50')
  await page.getByLabel(/Description/).fill('Quarterly consulting')
  await page.getByLabel(/Customer email or phone/).fill('customer@example.com')
  await page.getByRole('button', { name: /Create payment link/ }).click()

  await expect(page.getByRole('status')).toContainText('Payment link created')
  await expect(page.getByText('Quarterly consulting')).toBeVisible()
  await expect(page.getByText('customer@example.com')).toBeVisible()
  await page.getByRole('button', { name: /^Active/ }).click()
  await expect(page.getByText('Quarterly consulting')).toBeVisible()
  await page.getByRole('button', { name: /^Paid/ }).click()
  await expect(page.getByText('No paid links')).toBeVisible()
  await page.getByRole('button', { name: /^All/ }).click()
  await page.getByRole('button', { name: 'Mark Quarterly consulting as paid' }).click()
  await page.getByRole('button', { name: /^Paid/ }).click()
  await expect(page.getByText('Quarterly consulting')).toBeVisible()
})

test('creates a partial payment link, records payment, filters and persists after reload', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel(/Amount/).fill('120')
  await page.getByLabel(/Description/).fill('Milestone invoice')
  await page.getByLabel(/Customer email or phone/).fill('milestone@example.com')
  await page.getByLabel('Allow partial payments').check()
  await page.getByLabel('Minimum first payment').fill('25')
  await page.getByRole('button', { name: /Create payment link/ }).click()

  const link = page.locator('.link-card').filter({ hasText: 'Milestone invoice' })
  await expect(link).toContainText('Active')
  await link.getByLabel(/Record payment/).fill('30')
  await link.getByRole('button', { name: 'Record payment' }).click()
  await expect(link).toContainText('Partially paid')
  await expect(link).toContainText('Paid')
  await expect(link).toContainText('Due')
  await expect(link.locator('.payment-summary')).toContainText('₹30')
  await expect(link.locator('.payment-summary')).toContainText('₹90')
  await expect(link.locator('.link-meta')).toContainText(/\d{1,2}:\d{2}/)

  await page.getByRole('button', { name: /^Partially paid/ }).click()
  await expect(page.getByText('Milestone invoice')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /^Partially paid/ }).click()
  await expect(page.getByText('Milestone invoice')).toBeVisible()
  const restoredLink = page.locator('.link-card').filter({ hasText: 'Milestone invoice' })
  await expect(restoredLink).toContainText('Partially paid')
  await restoredLink.getByLabel(/Record payment/).fill('20')
  await restoredLink.getByRole('button', { name: 'Record payment' }).click()
  await expect(restoredLink.locator('.payment-summary')).toContainText('₹50')
  await expect(restoredLink.locator('.payment-summary')).toContainText('₹70')
})
